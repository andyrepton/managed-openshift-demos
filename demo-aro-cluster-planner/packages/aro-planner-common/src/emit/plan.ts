import type { CostEstimate, ModelComparison, PriceSource } from '../types.js';
import { STORAGE_TIER_LABEL, storageClassFor } from '../storage.js';
import type { EmitInput } from './types.js';

/**
 * The plan document: what was asked for, what it would cost, and on what basis.
 *
 * This is the artifact a platform engineer actually reads before approving, so
 * provenance is not a footnote. Every figure carries where it came from, and the
 * assumed ones are called out in their own section rather than mixed in with the
 * metered ones - the whole point of the comparison is lost if a 5x guess reads
 * like an Azure price.
 */

const money = (n: number) =>
  n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });

const SOURCE_LABEL: Record<PriceSource, string> = {
  'azure-api': 'Azure Retail Prices API',
  override: 'Configured locally',
  assumption: 'ASSUMPTION',
};

/** Markdown tables break on an unescaped pipe. */
const cell = (s: string) => s.replace(/\|/g, '\\|');

function costTable(estimate: CostEstimate): string[] {
  const rows = estimate.lines.map(l => {
    const amount = l.included ? `$${money(l.hourly)}` : '_excluded_';
    const note = l.sourceNote ? ` ${cell(l.sourceNote)}` : '';
    return `| ${cell(l.label)} | ${amount} | ${SOURCE_LABEL[l.source]} |${note ? ` ${note}` : ' |'}`;
  });

  return [
    '| Line | $/hr | Source | Note |',
    '| --- | --- | --- | --- |',
    ...rows.map(r => (r.endsWith('|') ? r : `${r} |`)),
  ];
}

function comparisonTable(comparison: ModelComparison[], chosen?: string): string[] {
  const rows = comparison.map(c => {
    const assumed = (c.estimate?.lines ?? []).every(l => l.source !== 'azure-api');
    const amount =
      c.amount === null
        ? '_unpriced_'
        : `${assumed ? '~' : ''}$${money(c.amount)}${c.billing === 'one-off' ? ' one-off' : '/month'}`;
    const basis = c.amount === null ? '--' : assumed ? 'Assumed' : 'Metered';
    const mark = c.model === chosen ? ' **(chosen)**' : '';
    return `| ${cell(c.label)}${mark} | ${amount} | ${basis} |`;
  });
  return ['| Where it runs | Cost | Basis |', '| --- | --- | --- |', ...rows];
}

export function renderPlanMarkdown(name: string, input: EmitInput): string {
  const { request, pool, comparison, networkPlan } = input;
  const model = request.deploymentModel ?? 'dedicated-cluster';
  const chosen = comparison.find(c => c.model === model);
  const onPrem = model === 'on-premises';
  const dedicated = model === 'dedicated-cluster';

  const out: string[] = [];

  out.push(`# Deployment plan: ${request.applicationName ?? name}`);
  out.push('');
  out.push(
    `Generated by the deployment planner${
      input.generatedAt ? ` on ${input.generatedAt}` : ''
    }. Namespace: \`${name}\`.`,
  );
  out.push('');

  // --- What was asked for ---------------------------------------------------
  out.push('## What was asked for');
  out.push('');
  out.push('| | |');
  out.push('| --- | --- |');
  out.push(`| Application | ${cell(request.applicationName ?? name)} |`);
  out.push(`| Where it runs | ${cell(chosen?.label ?? model)} |`);
  out.push(`| Capacity | ${request.vcpu} vCPU / ${request.ramGiB} GiB **allocatable** |`);
  if (input.plan?.storage) {
    const st = input.plan.storage;
    const sc = storageClassFor(st.tier);
    out.push(
      `| Persistent storage | ${st.requestedGiB} GiB on ${STORAGE_TIER_LABEL[st.tier]}, ` +
        `billed as a ${st.disk.name} at ${st.disk.gib} GiB |`,
    );
    out.push(
      `| StorageClass | \`${sc.name}\` (${sc.skuName})` +
        `${sc.mustCreate ? ' — **must be created**, ARO only provides `managed-csi`' : ' — the ARO default'} |`,
    );
  } else if ((request.storageGiB ?? 0) === 0) {
    out.push('| Persistent storage | None requested |');
  }
  out.push(`| Workload profile | ${request.profile} |`);
  if (!onPrem) {
    out.push(`| Architecture | ${request.flavour === 'hcp' ? 'ARO with hosted control planes' : 'ARO standard architecture'} |`);
    out.push(`| Azure region | ${request.region} |`);
    out.push(`| Availability zones | ${request.highAvailability ? 'Spread across three' : 'Single zone'} |`);
  }
  out.push('');
  out.push(
    'Capacity figures are allocatable, not raw: per-node OpenShift overhead is added ' +
      'on top before sizing. Sizing against raw VM specs under-provisions by roughly 15%.',
  );
  out.push('');

  // --- The comparison -------------------------------------------------------
  out.push('## Where it could run');
  out.push('');
  out.push(...comparisonTable(comparison, model));
  out.push('');

  const assumedModels = comparison.filter(
    c => c.estimate !== null && c.estimate.lines.every(l => l.source !== 'azure-api'),
  );
  if (assumedModels.length > 0) {
    out.push('> **Only the dedicated ARO cluster is priced from a real meter.**');
    out.push('>');
    for (const m of assumedModels) {
      out.push(`> - **${m.label}** — ${cell(m.estimate!.assumptions[0] ?? m.summary)}`);
    }
    out.push('>');
    out.push(
      '> These are not benchmarks and not Red Hat guidance. Replace them with your ' +
        'own figures before using this to decide anything.',
    );
    out.push('');
  }

  for (const c of comparison) {
    out.push(`### ${c.label}`);
    out.push('');
    out.push(c.summary);
    out.push('');
    for (const t of c.tradeoffs) out.push(`- ${t}`);
    out.push('');
  }

  // --- Cost -----------------------------------------------------------------
  out.push('## Cost');
  out.push('');
  if (chosen?.estimate) {
    const e = chosen.estimate;
    out.push(
      `**$${money(e.monthly)} / month** ($${money(e.hourly)}/hr, $${money(e.yearly)}/year) ` +
        `at ${e.hoursPerMonth} hours per month.`,
    );
    out.push('');
    out.push(...costTable(e));
    out.push('');
    if (e.assumptions.length > 0) {
      out.push('### Before you trust this number');
      out.push('');
      for (const a of e.assumptions) out.push(`- ${a}`);
      out.push('');
    }
  } else {
    out.push(
      `No costing is available for ${chosen?.label ?? model}. ${
        chosen?.unpricedReason ?? 'Unpriced does not mean free.'
      }`,
    );
    out.push('');
  }
  if (input.prices) {
    out.push(
      `Azure prices retrieved ${input.prices.retrievedAt}${
        input.prices.stale ? ' — **served from cache; Azure was unreachable**' : ''
      }.`,
    );
    out.push('');
  }

  // --- Node pool ------------------------------------------------------------
  if (dedicated && pool) {
    out.push('## Node pool');
    out.push('');
    out.push(`**${pool.nodes} x ${pool.sku.name}** — ${pool.totalVcpu} vCPU / ${pool.totalRamGiB} GiB raw, ` +
      `${pool.allocatableVcpu} vCPU / ${pool.allocatableRamGiB} GiB allocatable after overhead ` +
      `(${Math.round(pool.waste * 100)}% spare).`);
    out.push('');
    out.push('Why this one:');
    out.push('');
    for (const r of pool.rationale) out.push(`- ${r}`);
    out.push('');

    const alts = (input.alternatives ?? []).filter(a => a.sku.name !== pool.sku.name);
    if (alts.length > 0) {
      out.push('Also considered:');
      out.push('');
      out.push('| Option | Raw capacity | Spare |');
      out.push('| --- | --- | --- |');
      for (const a of alts) {
        out.push(
          `| ${a.nodes} x ${a.sku.name} | ${a.totalVcpu} vCPU / ${a.totalRamGiB} GiB | ${Math.round(a.waste * 100)}% |`,
        );
      }
      out.push('');
    }
  }

  // --- Networking -----------------------------------------------------------
  out.push('## Networking');
  out.push('');
  const settings = networkPlan.clusterSettings;
  out.push(`| Setting | Value |`);
  out.push(`| --- | --- |`);
  out.push(`| API visibility | ${settings.apiVisibility} |`);
  out.push(`| Ingress visibility | ${settings.ingressVisibility} |`);
  out.push(`| Outbound type | ${settings.outboundType} |`);
  out.push('');
  out.push(
    `${networkPlan.policies.length} NetworkPolicies are generated in ` +
      '`manifests/20-networkpolicies.yaml`: a default-deny baseline, the rules ' +
      'OpenShift itself needs, then one per connection requested.',
  );
  out.push('');
  if (networkPlan.caveats.length > 0) {
    out.push('### What NetworkPolicy cannot do here');
    out.push('');
    for (const c of networkPlan.caveats) out.push(`- ${c}`);
    out.push('');
  }

  // --- What happens next ----------------------------------------------------
  out.push('## What happens next');
  out.push('');
  if (dedicated) {
    out.push(`1. Review \`${name}.tfvars\`, then from \`andys-demo-cluster-tf\`:`);
    out.push('');
    out.push('   ```bash');
    out.push('   source ~/.secrets/tf-setup.sh');
    out.push(`   terraform plan -var-file=${name}.tfvars -out=tfplan`);
    out.push('   ```');
    out.push('');
    out.push('2. Once the cluster is up, apply the namespace manifests:');
    out.push('');
    out.push('   ```bash');
    out.push('   oc apply -f manifests/');
    out.push('   ```');
    if (request.flavour === 'classic') {
      out.push('');
      out.push(
        '   `30-machineset.yaml` carries `REPLACE_ME` placeholders that only exist ' +
          'once the cluster does. Fill them in before applying it.',
      );
    }
  } else if (onPrem) {
    out.push(
      'There is nothing to provision in Azure. Take the capacity figures and the ' +
        'networking requirements to whoever owns the on-premises platform. The ' +
        'namespace manifests apply unchanged to any OpenShift cluster:',
    );
    out.push('');
    out.push('```bash');
    out.push('oc apply -f manifests/');
    out.push('```');
  } else {
    out.push('No cluster is created. Apply the namespace manifests to the shared cluster:');
    out.push('');
    out.push('```bash');
    out.push('oc apply -f manifests/');
    out.push('```');
    out.push('');
    out.push(
      'The ResourceQuota caps this namespace at exactly the capacity that was ' +
        'costed, so check the shared cluster has that much headroom first.',
    );
  }
  out.push('');

  return `${out.join('\n')}\n`;
}
