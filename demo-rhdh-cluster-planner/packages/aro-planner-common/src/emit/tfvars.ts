import type { EmitFile, EmitInput } from './types.js';

/**
 * Terraform variables for `andys-demo-cluster-tf`.
 *
 * Targets exactly one module. The root module drives ROSA, ARO, ARO HCP and OSD
 * from a single state, so a tfvars that sets `create_` flags for more than one of
 * them will plan changes against clusters the request has nothing to do with.
 * Every file emitted here therefore states all four flags explicitly, with three
 * of them false, rather than relying on defaults.
 *
 * Only a dedicated cluster produces a tfvars at all. A namespace on an existing
 * cluster creates no infrastructure, and an on-premises request is not Terraform's
 * problem.
 */

const hcl = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

const CREATE_FLAGS = (which: 'aro_hcp' | 'aro') =>
  [
    `create_aro_hcp = ${which === 'aro_hcp'}`,
    `create_aro     = ${which === 'aro'}`,
    `create_rosa    = false`,
    `create_osd     = false`,
  ].join('\n');

const SHARED_HEADER = (input: EmitInput, name: string) =>
  [
    `# Generated by the deployment planner for ${name}.`,
    `#`,
    `# Apply against andys-demo-cluster-tf:`,
    `#`,
    `#   # with your Azure credentials exported:`,
    `#   terraform plan -var-file=${name}.tfvars -out=tfplan`,
    `#`,
    `# This file targets ONE module. Do not merge it with another cluster's tfvars -`,
    `# the root module shares one state across ROSA, ARO, ARO HCP and OSD, so a`,
    `# combined file plans destructive changes against whichever cluster is missing`,
    `# from it.`,
    `#`,
    `# Sized for ${input.request.vcpu} vCPU / ${input.request.ramGiB} GiB allocatable.`,
  ].join('\n');

/**
 * ARO HCP. The root module exposes node pools as a map keyed by ARM name, each
 * pinned to a single availability zone, so an even three-zone spread is three
 * pools rather than one pool with a zone list.
 */
function hcpTfvars(input: EmitInput, name: string): string {
  const { request, pool, networkPlan } = input;
  const settings = networkPlan.clusterSettings;
  const zones = request.highAvailability ? ['1', '2', '3'] : ['1'];
  const nodes = pool?.nodes ?? 3;
  const per = Math.ceil(nodes / zones.length);
  const vmSize = pool?.sku.name ?? 'Standard_D8as_v5';

  const pools = zones
    .map(
      (z, i) =>
        [
          `  np-${i + 1} = {`,
          `    vm_size           = ${hcl(vmSize)}`,
          `    replicas          = ${per}`,
          `    availability_zone = ${hcl(z)}`,
          `  }`,
        ].join('\n'),
    )
    .join('\n');

  // The two version variables take DIFFERENT shapes: the cluster takes an X.Y
  // stream and lets the platform pick the patch, while a node pool needs a full
  // X.Y.Z. Writing the same string to both produces a node pool version
  // Terraform rejects.
  const requested = request.openshiftVersion;
  const stream = (requested ?? '4.22').split('.').slice(0, 2).join('.');
  const nodePoolVersion = requested && /^\d+\.\d+\.\d+$/.test(requested) ? requested : null;

  return [
    SHARED_HEADER(input, name),
    ``,
    CREATE_FLAGS('aro_hcp'),
    ``,
    `aro_hcp_cluster_name       = ${hcl(name)}`,
    `aro_hcp_location           = ${hcl(request.region)}`,
    `aro_hcp_cluster_version    = ${hcl(stream)}`,
    ...(nodePoolVersion
      ? [`aro_hcp_node_pool_version  = ${hcl(nodePoolVersion)}`]
      : [
          `# aro_hcp_node_pool_version needs a full X.Y.Z and no specific patch was`,
          `# requested, so the module default applies. Pin it if the node kernel`,
          `# matters - the NVIDIA driver toolkit, for instance, builds against a`,
          `# specific one.`,
        ]),
    `aro_hcp_api_visibility     = ${hcl(settings.apiVisibility)}`,
    `aro_hcp_ingress_visibility = ${hcl(settings.ingressVisibility)}`,
    ``,
    `# Outbound type is ${settings.outboundType} for the connectivity requested, but the`,
    `# root module does not pass outbound_type through to ./aro-hcp yet. Set it on the`,
    `# module directly, or add the variable, if UserDefinedRouting matters here.`,
    ``,
    `aro_hcp_node_pools = {`,
    pools,
    `}`,
    ``,
  ].join('\n');
}

/**
 * Classic ARO. The root module only exposes the cluster name and version - worker
 * sizing is not a variable there - so the node pool is a day-2 MachineSet instead.
 * Saying so in the file is better than emitting variables Terraform will reject.
 */
function classicTfvars(input: EmitInput, name: string): string {
  const { request, pool } = input;
  return [
    SHARED_HEADER(input, name),
    ``,
    CREATE_FLAGS('aro'),
    ``,
    `aro_cluster_name      = ${hcl(name)}`,
    `aro_openshift_version = ${hcl(request.openshiftVersion ?? '4.17.27')}`,
    ``,
    `# Worker sizing is NOT set here. The ./aro module does not expose it as a root`,
    `# variable, so the pool recommended for this request -`,
    `# ${pool ? `${pool.nodes} x ${pool.sku.name}` : 'see the plan document'} -`,
    `# is applied after install as a MachineSet. See manifests/30-machineset.yaml.`,
    ``,
    `# API and ingress visibility are fixed by the ./aro module and are not`,
    `# variables. The requested visibility is recorded in plan.md.`,
    ``,
  ].join('\n');
}

/**
 * The tfvars for this request, or null when there is no cluster to create.
 *
 * Null is the honest answer for a shared namespace and for on-premises. Emitting
 * an empty or commented-out tfvars would suggest Terraform has something to do.
 */
export function renderTfvars(name: string, input: EmitInput): EmitFile | null {
  if (input.request.deploymentModel !== 'dedicated-cluster') return null;
  return {
    path: `${name}.tfvars`,
    contents:
      input.request.flavour === 'hcp' ? hcpTfvars(input, name) : classicTfvars(input, name),
  };
}
